/* ゲームルールの文章。スマホの「ルール」ポップアップに出す。
 *
 * 金額・階層の名前・パーツの名前・手札の上限は state から作る。
 * 数字を書き写すと、ルールを変えたときに説明だけ古くなるため。
 * 説明できない部分（カードの種類など）だけ、ここに文章で書いてある。
 */

import { moneyLabel, stageLabel } from "./format.js";

/** 階層ごとの値を「地上 200円 / 天空 2,000円 / 宇宙 20,000円」の形にする。fmt で書き方を変えられる。 */
function perStage(state, pick, fmt = moneyLabel) {
  return state.boards
    .map((b, i) => `${state.stages[i].name} ${fmt(pick(b))}`)
    .join(" / ");
}

/** [{ title, items: [文, ...] }, ...]。 */
export function rulesSections(state) {
  const top = state.stages[state.stages.length - 1];
  const stages = state.stages.map((_, i) => stageLabel(i + 1, state.stages)).join(" → ");
  const parts = state.part_kinds.map((k) => k.label).join("・");

  return [
    {
      title: "ゴールと勝ち方",
      items: [
        `${top.name}（最上階）で、パーツ（${parts}）を3種類そろえて「天国へ旅立つ」とクリア。ゲームがそこで終わります。`,
        "勝つのは、終わった時点で所持金がいちばん多い人。旅立った人とは限りません。",
        "ターン数の決まりはありません。誰かが旅立つか、「ゲーム終了」を押すまで続きます。",
      ],
    },
    {
      title: "あそびかた",
      items: [
        "自分の番に「サイコロをふる」を押すと、出目のぶんだけ盤を進みます。止まったマスの効果が起きます。",
        `盤はぐるっと一周つながっています。マス数は ${perStage(state, (b) => b.size, (n) => `${n}マス`)}。上の階層ほど広い盤です。手番は参加した順に回ります。`,
        `はじめの所持金は ${moneyLabel(state.start_money)}。`,
      ],
    },
    {
      title: "お金",
      items: [
        `スタートを通るたびに給料。${perStage(state, (b) => b.salary)}`,
        `半周（盤のちょうど真ん中のマス）を通るたびに大金。${perStage(state, (b) => b.half_bonus)}。ぴったり止まらなくても、通るだけでもらえます。`,
        "上の階層ほど、お金の桁が増えます。",
        "所持金は0円より下にはなりません。",
      ],
    },
    {
      title: "マスの効果",
      items: [
        "もらう：お金が増える　はらう：お金が減る",
        "ワープ：その数だけ、さらに進む　もどる：その数だけ下がる",
        "一回休み：次の自分の番を飛ばす",
        "カード：カードやパーツを1つもらう",
        "半周：通ると大金がもらえる専用のマス",
        "マスの内容は階層ごとに違います。",
      ],
    },
    {
      title: "階層とパーツ",
      items: [
        `階層は ${stages}。全員が最初は${state.stages[0].name}にいます。`,
        `パーツ（${parts}）はカードマスで出ます。3種類そろうと、自分の番に「登る」ボタンが出ます。`,
        "登ると、パーツが1つずつ消えて、自分だけ1階層上へ。マスの位置はそのままで、登っても番は続きます。",
        "パーツは手札に数えず、捨てることもできません。他の人には個数だけが見えます。",
      ],
    },
    {
      title: "カード",
      items: [
        `手札は${state.card_limit}枚まで。あふれたら、1枚すてるまでサイコロをふれません。`,
        "＋1・＋2・＋3マス：次にふるとき、出目に足して進む",
        "サイコロ2個：次にふるとき、2個ふって合計だけ進む",
        "おまもり：はらうマスで1回だけ払わずにすむ（持っているだけで自動）",
        "何を持っているかは自分だけに見えます。",
      ],
    },
  ];
}
